// High-performance 2D Clifford Element Structure
struct Clifford2D {
    int64_t x = 0;
    int64_t y = 0;

    double norm_sq() const {
        return static_cast<double>(x * x + y * y);
    }

    void add_element(int16_t dx, int16_t dy) {
        x += dx;
        y += dy;
    }
};

// High-speed Fermat Decomposer checking sums of two squares
bool fast_decompose_two_square(uint64_t p, int16_t& x, int16_t& y) {
    if (p == 2) { x = 1; y = 1; return true; }
    if ((p & 3) != 1) return false; 

    uint64_t limit_x = static_cast<uint64_t>(std::sqrt(p));
    for (uint64_t tx = limit_x; tx > 0; --tx) {
        uint64_t rem = p - (tx * tx);
        uint64_t ty = static_cast<uint64_t>(std::sqrt(rem));
        if (tx * tx + ty * ty == p) {
            x = static_cast<int16_t>(tx);
            y = static_cast<int16_t>(ty);
            return true;
        }
    }
    return false;
}

// Optimized Linear Sieve for generation of base prime matrices
std::vector<uint64_t> generate_high_range_primes(uint64_t limit) {
    std::vector<bool> is_prime(limit + 1, true);
    std::vector<uint64_t> primes;
    if (limit >= 2) primes.push_back(2);
    for (uint64_t i = 3; i * i <= limit; i += 2) {
        if (is_prime[i]) {
            for (uint64_t j = i * i; j <= limit; j += i * 2) is_prime[j] = false;
        }
    }
    for (uint64_t i = 3; i <= limit; i += 2) {
        if (is_prime[i]) primes.push_back(i);
    }
    return primes;
}

int main() {
    mkdir("output", 0777);

    // Target a limit to process a highly descriptive arithmetic tracking horizon
    uint64_t upper_bound_limit = 100000; 
    std::vector<uint64_t> base_primes = generate_high_range_primes(upper_bound_limit);
    
    std::vector<uint64_t> test_primes;
    for (auto p : base_primes) {
        if (p == 2 || (p % 4 == 1)) {
            test_primes.push_back(p);
        }
    }

    size_t total_primes = test_primes.size();
    
    std::vector<double> res_track_A(total_primes, 0.0);
    std::vector<double> res_track_B(total_primes, 0.0);
    std::vector<double> results_bound(total_primes, 0.0);
    std::vector<double> optimized_thetas(total_primes, 0.0);

    std::vector<int16_t> comp_x(total_primes, 0), comp_y(total_primes, 0);
    std::vector<bool> decomposable(total_primes, false);

    std::cout << "[SYSTEM] Phase 1: Processing parallelized 2D Fermat decompositions..." << std::endl;

    #pragma omp parallel for schedule(static)
    for (size_t idx = 0; idx < total_primes; ++idx) {
        decomposable[idx] = fast_decompose_two_square(test_primes[idx], comp_x[idx], comp_y[idx]);
    }

    std::cout << "[SYSTEM] Phase 2: Running deterministic Clifford stabilization..." << std::endl;

    const int perm_patterns[2][2] = { {0, 1}, {1, 0} };
    const int sign_patterns[4][2] = { {1, 1}, {1, -1}, {-1, 1}, {-1, -1} };

    Clifford2D track_A; 
    Clifford2D track_B; 

    for (size_t idx = 0; idx < total_primes; ++idx) {
        if (!decomposable[idx]) continue;

        uint64_t p = test_primes[idx];
        int16_t source_coords[2] = { comp_x[idx], comp_y[idx] };

        track_A.add_element(source_coords[0], source_coords[1]);

        double b_best_norm_sq = 1e300;
        int16_t b_chosen_dx = 0, b_chosen_dy = 0;

        for (int p_idx = 0; p_idx < 2; ++p_idx) {
            int64_t cx = source_coords[perm_patterns[p_idx][0]];
            int64_t cy = source_coords[perm_patterns[p_idx][1]];

            for (int s_idx = 0; s_idx < 4; ++s_idx) {
                int16_t sx = static_cast<int16_t>(cx * sign_patterns[s_idx][0]);
                int16_t sy = static_cast<int16_t>(cy * sign_patterns[s_idx][1]);

                Clifford2D candidate_state = track_B;
                candidate_state.add_element(sx, sy);
                double candidate_norm_sq = candidate_state.norm_sq();

                if (candidate_norm_sq < b_best_norm_sq) {
                    b_best_norm_sq = candidate_norm_sq;
                    b_chosen_dx = sx;
                    b_chosen_dy = sy;
                }
            }
        }
        track_B.add_element(b_chosen_dx, b_chosen_dy);

        res_track_A[idx] = std::sqrt(track_A.norm_sq());
        res_track_B[idx] = std::sqrt(track_B.norm_sq());
        results_bound[idx] = 1.3 * std::sqrt(static_cast<double>(p));
        
        // Extract the optimized angular phase assignment generated by the bivector plane
        optimized_thetas[idx] = std::atan2(static_cast<double>(b_chosen_dy), static_cast<double>(b_chosen_dx));
    }

    // Write trajectory logging matrices
    std::ofstream csv_file("output/fermat_bivector_comparative_res.csv");
    csv_file << "Prime,Track_A_Raw,Track_B_Greedy,Spectral_Bound\n";
    csv_file << std::fixed << std::setprecision(5);
    for (size_t i = 0; i < total_primes; ++i) {
        if (test_primes[i] == 0) continue;
        csv_file << test_primes[i] << "," << res_track_A[i] << "," << res_track_B[i] << "," << results_bound[i] << "\n";
    }
    csv_file.close();

    std::cout << "[SYSTEM] Phase 3: Evaluating Dirichlet L-function over critical line..." << std::endl;

    // Sweeping through the critical line parameters t from 0 to 100 with delta = 0.05
    double t_start = 0.0;
    double t_end = 100.0;
    double t_delta = 0.05;
    size_t total_t_steps = static_cast<size_t>((t_end - t_start) / t_delta) + 1;

    std::vector<double> t_values(total_t_steps, 0.0);
    std::vector<double> l_real(total_t_steps, 0.0);
    std::vector<double> l_imag(total_t_steps, 0.0);
    std::vector<double> l_magnitude(total_t_steps, 0.0);

    // Multithreaded loop over spectral critical intervals to prevent lock delays
    #pragma omp parallel for schedule(dynamic)
    for (size_t t_idx = 0; t_idx < total_t_steps; ++t_idx) {
        double t = t_start + static_cast<double>(t_idx) * t_delta;
        t_values[t_idx] = t;

        double sum_real = 1.0; 
        double sum_imag = 0.0;

        for (size_t p_idx = 0; p_idx < total_primes; ++p_idx) {
            if (!decomposable[p_idx]) continue;

            double p = static_cast<double>(test_primes[p_idx]);
            double theta = optimized_thetas[p_idx];
            
            // Analytic Gaussian damping system to secure spectral domain convergence
            double damping = std::exp(-p / 10000.0); 
            double amplitude = std::pow(p, -0.5) * damping;
            
            // Total phase mapping combination: Geometric theta minus the analytical Dirichlet trace
            double dynamic_phase = theta - (t * std::log(p));

            sum_real += amplitude * std::cos(dynamic_phase);
            sum_imag += amplitude * std::sin(dynamic_phase);
        }

        l_real[t_idx] = sum_real;
        l_imag[t_idx] = sum_imag;
        l_magnitude[t_idx] = std::sqrt(sum_real * sum_real + sum_imag * sum_imag);
    }

    // Write out Dirichlet L-function tracking telemetry log profiles
    std::ofstream l_file("output/dirichlet_l_critical_line.csv");
    l_file << "t,Real,Imag,Magnitude\n";
    l_file << std::fixed << std::setprecision(6);
    for (size_t i = 0; i < total_t_steps; ++i) {
        l_file << t_values[i] << "," << l_real[i] << "," << l_imag[i] << "," << l_magnitude[i] << "\n";
    }
    l_file.close();

    std::cout << "\n=========================================================" << std::endl;
    std::cout << "[COMPLETE] Metrics compiled successfully across active matrices." << std::endl;
    std::cout << "[COMPLETE] Trajectories: output/fermat_bivector_comparative_res.csv" << std::endl;
    std::cout << "[COMPLETE] Spectral L-Data: output/dirichlet_l_critical_line.csv" << std::endl;
    std::cout << "=========================================================" << std::endl;

    return 0;
}
